#!/bin/sh
set -eu

say() { printf '%s\n' "$*"; }
die() { printf 'HelloWM installer: %s\n' "$*" >&2; exit 1; }

# Run as the desktop user. The script asks sudo only for system-wide paths.
[ "$(id -u)" -ne 0 ] || die "Run this as your normal user, not with sudo. The script will use sudo for system files."

SCRIPT_DIR=$(CDPATH= cd "$(dirname "$0")" && pwd)
BIN_SOURCE="$SCRIPT_DIR/target/release/hellowm"
CONFIG_DIR="$HOME/.config/hellowm"
STATE_DIR="$HOME/.local/state/hellowm"
MANIFEST="$STATE_DIR/install-manifest"
HELPERS_DIR="$HOME/.local/libexec/hellowm"
ASSET_DIR="$HOME/.config/assets"
ASSET_PATH="$ASSET_DIR/windows.png"
CREATED_START_ASSET=no
XINITRC="$HOME/.xinitrc"
XINITRC_TEMPLATE="$CONFIG_DIR/xinitrc.hellowm-template"

OS_ID=unknown
if [ -r /etc/os-release ]; then
    # shellcheck disable=SC1091
    . /etc/os-release
    OS_ID=${ID:-unknown}
fi
if [ -e /etc/NIXOS ] || [ "$OS_ID" = nixos ]; then
    INSTALL_MODE=nixos
else
    # Debian, Ubuntu, Mint, Fedora, Arch, openSUSE, etc. use normal X11 paths.
    INSTALL_MODE=generic
fi

as_root() {
    if [ "$(id -u)" -eq 0 ]; then
        "$@"
    elif command -v sudo >/dev/null 2>&1; then
        sudo "$@"
    else
        die "sudo is required to install files outside your home directory."
    fi
}

# Build from source when Cargo is available; otherwise accept an already-built binary.
if command -v cargo >/dev/null 2>&1; then
    say "Building HelloWM in release mode..."
    (cd "$SCRIPT_DIR" && cargo build --release)
elif [ ! -x "$BIN_SOURCE" ]; then
    die "Cargo is not installed and target/release/hellowm does not exist. Install Rust/Cargo or build with 'cargo build --release' first."
else
    say "Cargo not found; using existing $BIN_SOURCE"
fi
[ -x "$BIN_SOURCE" ] || die "Build did not produce target/release/hellowm."

mkdir -p "$CONFIG_DIR" "$STATE_DIR" "$HELPERS_DIR" "$ASSET_DIR"
if [ ! -e "$CONFIG_DIR/config.toml" ]; then
    install -m 644 "$SCRIPT_DIR/examples/config.toml" "$CONFIG_DIR/config.toml"
    say "Created $CONFIG_DIR/config.toml"
fi
install -m 755 "$SCRIPT_DIR/scripts/about-computer.sh" "$HELPERS_DIR/about-computer.sh"
install -m 755 "$SCRIPT_DIR/scripts/create-launcher.sh" "$HELPERS_DIR/create-launcher.sh"
if [ ! -e "$ASSET_PATH" ]; then
    install -m 644 "$SCRIPT_DIR/assets/windows.png" "$ASSET_PATH"
    CREATED_START_ASSET=yes
    say "Installed default Start icon at $ASSET_PATH"
fi

if [ "$INSTALL_MODE" = nixos ]; then
    BIN_PATH="$HOME/.local/bin/hellowm"
else
    PREFIX=${PREFIX:-/usr/local}
    BINDIR=${BINDIR:-$PREFIX/bin}
    XSESSIONDIR=${XSESSIONDIR:-/usr/share/xsessions}
    BIN_PATH="$BINDIR/hellowm"
fi

CREATED_XINITRC=no
if [ ! -e "$XINITRC" ]; then
    mkdir -p "$(dirname "$XINITRC_TEMPLATE")"
    cat > "$XINITRC_TEMPLATE" <<EOF_XINIT
# Generated by HelloWM install.sh. Add your wallpaper command above exec.
# xwallpaper --zoom "$HOME/Pictures/wallpaper.jpg"
# feh --bg-fill "$HOME/Pictures/wallpaper.jpg"
exec "$BIN_PATH"
EOF_XINIT
    cp "$XINITRC_TEMPLATE" "$XINITRC"
    chmod 755 "$XINITRC"
    CREATED_XINITRC=yes
    say "Created $XINITRC for startx"
else
    say "Keeping existing $XINITRC unchanged. Add 'exec hellowm' (or the installed binary path) to it to use startx."
fi

if [ "$INSTALL_MODE" = nixos ]; then
    BIN_PATH="$HOME/.local/bin/hellowm"
    MODULE_PATH="$CONFIG_DIR/nixos-session.nix"
    mkdir -p "$HOME/.local/bin"

    if [ -e "$BIN_PATH" ] && [ ! -f "$MANIFEST" ]; then
        die "$BIN_PATH already exists and is not managed by this installer; move it aside before installing."
    fi
    if [ -e "$MODULE_PATH" ] && [ ! -f "$MANIFEST" ]; then
        die "$MODULE_PATH already exists; move it aside before installing so it is not overwritten."
    fi

    install -m 755 "$BIN_SOURCE" "$BIN_PATH"
    # Expand only the binary placeholder; the Nix expressions in the template stay intact.
    escaped_bin=$(printf '%s' "$BIN_PATH" | sed 's/[&|]/\\&/g')
    sed "s|@HELLOWM_BIN@|$escaped_bin|g" "$SCRIPT_DIR/nixos/installed-session.nix.in" > "$MODULE_PATH"
    chmod 644 "$MODULE_PATH"

    cat > "$MANIFEST" <<EOF_MANIFEST
MODE=nixos
BIN_PATH=$BIN_PATH
MODULE_PATH=$MODULE_PATH
HELPERS_DIR=$HELPERS_DIR
ASSET_PATH=$ASSET_PATH
CREATED_START_ASSET=$CREATED_START_ASSET
CREATED_XINITRC=$CREATED_XINITRC
XINITRC_TEMPLATE=$XINITRC_TEMPLATE
EOF_MANIFEST

    say ""
    say "NixOS detected. HelloWM was installed to $BIN_PATH."
    say "The LightDM/SDDM session is provided declaratively by:"
    say "  $MODULE_PATH"
    say ""
    say "Add this path to the existing imports list in /etc/nixos/configuration.nix:"
    say "  $MODULE_PATH"
    say "Then rebuild: sudo nixos-rebuild switch"
    say "Do not add a second 'imports' attribute if the file already has one; add the path to its existing list."
else
    SESSION_FILE="$XSESSIONDIR/hellowm.desktop"

    if [ -e "$BIN_PATH" ] && [ ! -f "$MANIFEST" ]; then
        die "$BIN_PATH already exists and is not managed by this installer; move it aside before installing."
    fi
    if [ -e "$SESSION_FILE" ] && [ ! -f "$MANIFEST" ]; then
        die "$SESSION_FILE already exists and is not managed by this installer; move it aside before installing."
    fi

    as_root install -d "$BINDIR" "$XSESSIONDIR"
    as_root install -m 755 "$BIN_SOURCE" "$BIN_PATH"

    tmp_desktop=$(mktemp)
    cat > "$tmp_desktop" <<EOF_DESKTOP
[Desktop Entry]
Name=HelloWM
Comment=A minimal floating X11 desktop with a Windows-inspired taskbar
Exec=$BIN_PATH
TryExec=$BIN_PATH
Type=XSession
DesktopNames=HelloWM
EOF_DESKTOP
    as_root install -m 644 "$tmp_desktop" "$SESSION_FILE"
    rm -f "$tmp_desktop"

    cat > "$MANIFEST" <<EOF_MANIFEST
MODE=generic
BIN_PATH=$BIN_PATH
SESSION_FILE=$SESSION_FILE
HELPERS_DIR=$HELPERS_DIR
ASSET_PATH=$ASSET_PATH
CREATED_START_ASSET=$CREATED_START_ASSET
CREATED_XINITRC=$CREATED_XINITRC
XINITRC_TEMPLATE=$XINITRC_TEMPLATE
EOF_MANIFEST

    say ""
    say "HelloWM installed."
    say "Binary:  $BIN_PATH"
    say "Session: $SESSION_FILE"
    say "Log out and select HelloWM from your display manager, or run startx from a TTY."
    say "Detected OS: $OS_ID (using generic Linux paths)."
fi

say "User configuration: $CONFIG_DIR/config.toml"
say "Uninstall with ./uninstall.sh (add --purge-config to remove your settings too)."
